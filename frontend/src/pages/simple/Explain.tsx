import { api, type Agents } from "../../api";
import { AskAgents } from "../../components/AskAgents";
import { Details, SCard, SimpleLoading, SimpleReplay } from "../../components/simple";
import { ErrorState } from "../../components/ui";
import { longDate, nice } from "../../format";
import { useAsync } from "../../hooks";
import { edgePlain, newsRow, toneWord } from "../../plain";
import { useRoute } from "../../state";
import type { Edge } from "../../api";

export default function Explain() {
  const { date, pf } = useRoute();
  const a = useAsync(() => api.agents(date), [date]);
  const net = useAsync(() => api.network(date), [date]);
  return (
    <div className="space-y-5">
      <SimpleReplay />
      <AskAgents compact portfolio={pf} />
      {a.error ? <ErrorState message={a.error} /> : !a.data ? <SimpleLoading /> : <Body a={a.data} edges={net.data?.edges ?? []} />}
    </div>
  );
}

function Body({ a, edges }: { a: Agents; edges: Edge[] }) {
  const { setDate } = useRoute();
  const macro = a.agents.macro.evidence;
  const val = (p: string) => macro.find((i) => i.id.startsWith(p));
  const vix = val("macro:VIXCLS"), nfci = val("macro:NFCI"), baa = val("macro:BAA10Y"), alert = val("alert:");
  const turnover = a.agents.graph.evidence.find((i) => i.id.includes("vl_shd_b0@"));
  const news = newsRow(a);
  return (
    <>
      <SCard kicker={`Rule-based briefing · ${longDate(a.date)}`} title="The evidence each agent works from — summarised by fixed rules">
        <p className="text-muted">Each agent only looks at information that was public before the market closed that day. This
          summary is generated by fixed rules (no AI), so every sentence can be checked — it is always available, even without the AI model.</p>
        <div className="mt-4 grid gap-4 lg:grid-cols-3" data-testid="agent-summaries">
          <Agent color="#9085e9" name="Graph agent" role="relationships between assets">
            {turnover ? `${turnover.values.value} links between assets changed versus the week before — ${toneWord(turnover.values.pct)} for the past 5 years.` : "No relationship data for this date."}
            {edges[0] && <> The biggest change: {edgePlain(edges[0])}</>}
          </Agent>
          <Agent color="#d95926" name="Macro agent" role="economic & market indicators">
            {vix && `Fear gauge (VIX) ${vix.values.value} — ${toneWord(vix.values.pct)}. `}
            {nfci && `Borrowing conditions ${nfci.values.value > 0 ? "tighter" : "looser"} than average. `}
            {baa && `Corporate credit premium ${toneWord(baa.values.pct)}.`}
          </Agent>
          <Agent color="#199e70" name="News agent" role="headlines before the close">
            {news.text}
          </Agent>
        </div>
        <div className="mt-5 rounded-xl border border-ink/30 bg-panel2 p-5" data-testid="synthesis-simple">
          <div className="text-[13px] font-semibold uppercase tracking-[0.14em] text-muted">Synthesis agent · putting it together</div>
          <p className="mt-1 text-[17px]">{alert ? (alert.values.score >= alert.values.threshold
            ? `The warning model raised an alert (score ${alert.values.score.toFixed(2)} vs alert line ${alert.values.threshold.toFixed(2)}).`
            : `The warning model did not raise an alert (score ${alert.values.score.toFixed(2)} vs alert line ${alert.values.threshold.toFixed(2)}).`) : ""}
            {" "}The evidence above is what was observable at the close; it describes conditions, it does not predict what happened next.</p>
          {a.agents.news.abstained && <p className="mt-2 text-warn">The news agent had nothing to read for this date, so this briefing rests on market and relationship data only.</p>}
        </div>
        <Details label="Show the detailed evidence (every source, with timestamps)" testid="details-evidence">
          <ul className="space-y-3">
            {[...a.agents.macro.evidence, ...a.agents.graph.evidence, ...a.agents.news.evidence].map((i) => (
              <li key={i.id}><div className="text-ink/90">{nice(i.description)}</div><div className="font-mono text-[12px] text-dim">{i.id} · available {i.available.slice(0, 16)}</div></li>
            ))}
          </ul>
        </Details>
        <Details label="Show the AI-written draft (unverified)" testid="details-llm">
          {a.llm_draft ? (
            <div>
              <div className={`rounded-lg border p-3 ${a.llm_draft.flags.length ? "border-crit/50 bg-crit/10 text-[#ff9c9c]" : "border-warn/50 bg-warn/10 text-warn"}`}>
                <b>Unverified draft written by a local language model.</b> It is not a verified conclusion. In our held-out check, 73% of
                its statements (24 of 33) were faithful to the evidence — below our 90% target.
                {a.llm_draft.flags.map((f) => <div key={f} className="mt-1 text-[14px]">⚠ {f}</div>)}
              </div>
              <ul className="mt-3 list-disc space-y-1 pl-6 text-ink/80">{a.llm_draft.claims.map((c, i) => <li key={i}>“{c.text}”</li>)}</ul>
            </div>
          ) : (
            <div>
              <p className="text-muted">No AI-written draft exists for this date (drafts were generated for 24 evaluated alerts only). Try one of these dates:</p>
              <div className="mt-2 flex flex-wrap gap-2">{a.llm_draft_available_for.slice(0, 12).map((d) => (
                <button key={d} type="button" onClick={() => setDate(d)} className="rounded-md border border-line px-2 py-1 font-mono text-[13px] text-muted hover:text-ink">{d}</button>))}</div>
            </div>
          )}
        </Details>
        <Details label="How reliable is this model? (from our evaluation, not known on this date)">
          <ul className="list-disc space-y-1 pl-6 text-muted">{a.reliability_retrospective.map((r) => <li key={r}>{r.replace(/^\[retrospective[^\]]*\] /, "")}</li>)}</ul>
        </Details>
      </SCard>
    </>
  );
}

function Agent({ color, name, role, children }: { color: string; name: string; role: string; children: React.ReactNode }) {
  return (
    <div className="rounded-xl border bg-panel2 p-4" style={{ borderColor: color }}>
      <div className="flex items-center gap-2 text-[17px] font-semibold"><span className="h-3 w-3 rounded-full" style={{ background: color }} />{name}</div>
      <div className="text-[14px] text-muted">{role}</div>
      <p className="mt-2 text-[16px]">{children}</p>
    </div>
  );
}
