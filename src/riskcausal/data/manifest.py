"""Render DATASET_MANIFEST.md from the JSON verification report (never hand-written)."""

from __future__ import annotations

from pathlib import Path

from riskcausal.config import PROJECT_ROOT


def _md_table(rows: list[dict], cols: list[str]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join("" if r.get(c) is None else str(r.get(c)) for c in cols) + " |")
    return "\n".join(out)


def write_manifest(report: dict, path: Path, json_path: Path) -> None:
    L: list[str] = []
    L += ["# DATASET_MANIFEST", "",
          (f"_Auto-generated by `riskcausal verify-data` from `{json_path.relative_to(PROJECT_ROOT)}` "
          f"(snapshot {report['snapshot']}). Do not edit by hand — re-run the command._"), "",
          f"Study start date: **{report['study_start']}**. All numbers below come from executed downloads.", ""]

    etfs = report["etfs"]
    ok = [e for e in etfs if e["status"] == "ok"]
    L += ["## 1. ETFs (Yahoo Finance via yfinance, adjusted for splits & dividends)", "",
          (f"Downloaded OK: **{len(ok)}/{len(etfs)}**. "
          f"Available from study start: **{sum(e.get('starts_by_study_start', False) for e in ok)}**."), "",
          ("`missing_session_rate` = share of NYSE sessions between max(first date, study start) and last date "
          "with no bar."), "",
          _md_table(etfs, ["ticker", "name", "status", "first_date", "last_date", "starts_by_study_start",
                           "n_rows_since_start", "missing_session_rate", "nan_close", "zero_volume_days",
                           "max_abs_daily_logret", "error"]), ""]

    fred = report["fred"]
    rows = []
    for f in fred:
        a = f.get("alfred")
        a_str = a if isinstance(a, str) else (
            f"ok: {a['n_vintages']} vintages {a['first_vintage']}→{a['last_vintage']}" if a.get("status") == "ok"
            else f"FAILED: {a.get('error')}")
        rows.append({**f, "alfred_vintages": a_str})
    L += ["## 2. FRED / ALFRED macro series", "",
          (f"FRED API key present: **{report['fred_api_key_present']}** (free key; required only for ALFRED "
          "vintages). Current-vintage values come from the public `fredgraph.csv` endpoint."), "",
          _md_table(rows, ["series_id", "name", "freq", "revised", "status", "first_date", "last_date",
                           "covers_study_start", "n_obs", "missing_rate_since_start", "alfred_vintages",
                           "error"]), "",
          "`missing_rate_since_start` for daily series counts FRED's own blank days (mostly market holidays).", ""]

    fn = report["fnspid"]
    L += ["## 3. FNSPID news (Hugging Face `" + fn.get("repo", "") + "`)", "", f"Status: **{fn['status']}**"]
    if fn["status"] == "ok":
        info = fn["info"]
        L += [(f"- private: {info['private']}, gated: {info['gated']}, last modified: {info['last_modified']}, "
              f"licence field: {info['license']}"), "", "Files:", ""]
        L += [f"- `{f['path']}` — {round((f['size_bytes'] or 0) / 1e9, 2)} GB" for f in fn["files"]]
        L += ["", ("Sampled content (byte-range reads at 21 evenly spaced offsets — **a sample, not a full scan**; "
              "exact coverage of Feb–Mar 2020 and Mar 2023 is confirmed only after the full download in M6). "
              "Article bodies contain quoted multi-line text, so reads starting mid-file are often misaligned; "
              "the raw probes (incl. garbled ticker fields) are kept in the JSON report:"), ""]
        for p, s in fn["samples"].items():
            if s["status"] != "ok":
                L.append(f"- `{p}`: FAILED — {s.get('error')}")
                continue
            L.append(f"- `{p}` ({s['size_gb']} GB): columns `{s['columns']}`; sampled date range "
                     f"**{s['sampled_min_date']} → {s['sampled_max_date']}**")
    else:
        L.append(f"- error: {fn.get('error')}")
    L += ["", "## 4. GDELT (optional supplement)", "", (f"Status: **{report['gdelt']['status']}** — "
          f"{report['gdelt'].get('note') or report['gdelt'].get('error')}"), ""]

    # Decisions the data forces
    failed = [e["ticker"] for e in etfs if e["status"] != "ok"]
    late = [f"{e['ticker']} ({e['first_date']})" for e in ok if not e["starts_by_study_start"]]
    short_fred = [f"{f['series_id']} (from {f['first_date']})" for f in fred
                  if f["status"] == "ok" and not f["covers_study_start"]]
    pending = [f["series_id"] for f in fred if isinstance(f.get("alfred"), str) and f["alfred"].startswith("PENDING")]
    L += ["## 5. Findings that affect the plan", "",
          f"- ETF downloads failed: {failed or 'none'}",
          f"- ETFs listed after study start (ragged panel, E2): {late or 'none'}",
          f"- FRED series not covering study start: {short_fred or 'none'}",
          f"- Revised series still lacking point-in-time vintages: {pending or 'none'}"
          + (" — **these may not be used as features/baselines until vintages are downloaded**" if pending else ""),
          ""]
    path.write_text("\n".join(L))
